create table if not exists public.job_applications (
  id bigint generated by default as identity primary key,
  application_id text not null unique,
  job_title text not null,
  destination text not null,
  full_name text not null,
  phone text not null,
  email text not null default '',
  experience text not null default '',
  notes text not null default '',
  cv_name text not null,
  cv_type text not null,
  cv_size integer not null check (cv_size between 1 and 5242880),
  cv_data text not null,
  status text not null default 'New'
    check (status in ('New', 'Reviewed', 'Shortlisted', 'Rejected')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.job_applications
  add column if not exists updated_at timestamptz not null default now();

update public.job_applications
set status = 'New'
where status is null or status = 'pending';

alter table public.job_applications
  alter column status set default 'New',
  alter column status set not null;

create index if not exists job_applications_created_at_idx
  on public.job_applications(created_at desc);

create or replace function public.job_application_analytics()
returns jsonb
language sql
security definer
set search_path = ''
as $$
  select jsonb_build_object(
    'total',
      (select count(*) from public.job_applications),
    'last30Days',
      (select count(*) from public.job_applications
       where created_at >= now() - interval '30 days'),
    'byStatus',
      jsonb_build_object(
        'New', (select count(*) from public.job_applications where status = 'New'),
        'Reviewed', (select count(*) from public.job_applications where status = 'Reviewed'),
        'Shortlisted', (select count(*) from public.job_applications where status = 'Shortlisted'),
        'Rejected', (select count(*) from public.job_applications where status = 'Rejected')
      ),
    'monthly',
      coalesce((
        select jsonb_agg(jsonb_build_object('month', month, 'count', application_count) order by month)
        from (
          select to_char(date_trunc('month', created_at), 'YYYY-MM') as month, count(*) as application_count
          from public.job_applications
          where created_at >= date_trunc('month', now()) - interval '5 months'
          group by date_trunc('month', created_at)
        ) monthly_counts
      ), '[]'::jsonb),
    'topJobs',
      coalesce((
        select jsonb_agg(
          jsonb_build_object('job_title', job_title, 'destination', destination, 'count', application_count)
          order by application_count desc, job_title
        )
        from (
          select job_title, destination, count(*) as application_count
          from public.job_applications
          group by job_title, destination
          order by application_count desc, job_title
          limit 5
        ) top_jobs
      ), '[]'::jsonb)
  )
$$;

