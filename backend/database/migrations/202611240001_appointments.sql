create table if not exists public.appointment_requests (
  id bigint generated by default as identity primary key,
  request_id text not null unique,
  service_type text not null check (
    service_type in ('vehicle_inspection', 'property_viewing', 'sanitation_service')
  ),
  target text not null,
  client_name text not null,
  client_phone text not null,
  preferred_date text not null,
  preferred_time text not null,
  location text not null default '',
  location_latitude double precision,
  location_longitude double precision,
  notes text not null default '',
  status text not null default 'Requested'
    check (status in ('Requested', 'Confirmed', 'Completed', 'Cancelled')),
  notification_status text not null default 'pending'
    check (notification_status in ('pending', 'sent', 'failed', 'not_configured')),
  notification_error text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check ((location_latitude is null) = (location_longitude is null)),
  check (location_latitude is null or location_latitude between -90 and 90),
  check (location_longitude is null or location_longitude between -180 and 180)
);

alter table public.appointment_requests
  add column if not exists notification_status text not null default 'pending',
  add column if not exists notification_error text,
  add column if not exists updated_at timestamptz not null default now();

update public.appointment_requests
set status = 'Requested'
where status is null or status = 'pending';

alter table public.appointment_requests
  alter column status set default 'Requested';

create index if not exists appointment_requests_schedule_idx
  on public.appointment_requests(preferred_date, preferred_time, created_at desc);

alter table public.appointment_requests enable row level security;
revoke all on public.appointment_requests from public, anon, authenticated;
grant all on public.appointment_requests to service_role;
grant usage, select on sequence public.appointment_requests_id_seq to service_role;

notify pgrst, 'reload schema';
