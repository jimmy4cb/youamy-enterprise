create table if not exists public.admin_users (
  id bigint generated by default as identity primary key,
  name text not null,
  email text not null unique,
  password_hash text not null,
  role text not null,
  totp_secret text,
  active boolean not null default true,
  created_at timestamptz not null default now()
);

alter table public.admin_users
  alter column role drop default,
  alter column role set not null,
  alter column active set default true,
  alter column active set not null;

do $$
begin
  if exists (
    select 1
    from public.admin_users
    where role not in (
      'super_admin',
      'listings_admin',
      'orders_admin',
      'support_agent',
      'content_editor'
    )
  ) then
    raise exception 'admin_users contains unsupported roles; resolve them before applying this migration';
  end if;

  if not exists (
    select 1
    from pg_constraint
    where conrelid = 'public.admin_users'::regclass
      and conname = 'admin_users_role_check'
  ) then
    alter table public.admin_users
      add constraint admin_users_role_check
      check (role in (
        'super_admin',
        'listings_admin',
        'orders_admin',
        'support_agent',
        'content_editor'
      ));
  end if;
end
$$;

create table if not exists public.admin_sessions (
  id text primary key,
  user_id bigint not null references public.admin_users(id) on delete cascade,
  expires_at timestamptz not null,
  created_at timestamptz not null default now()
);

create index if not exists admin_sessions_user_id_idx
  on public.admin_sessions(user_id);
create index if not exists admin_sessions_expires_at_idx
  on public.admin_sessions(expires_at);

create table if not exists public.admin_pending_logins (
  token text primary key,
  user_id bigint not null references public.admin_users(id) on delete cascade,
  setup_secret text,
  expires_at timestamptz not null,
  created_at timestamptz not null default now()
);

create index if not exists admin_pending_logins_expires_at_idx
  on public.admin_pending_logins(expires_at);

alter table public.admin_users enable row level security;
alter table public.admin_sessions enable row level security;
alter table public.admin_pending_logins enable row level security;

revoke all on public.admin_users, public.admin_sessions, public.admin_pending_logins
  from public, anon, authenticated;
grant all on public.admin_users, public.admin_sessions, public.admin_pending_logins
  to service_role;
grant usage, select on sequence public.admin_users_id_seq to service_role;

notify pgrst, 'reload schema';
