CREATE TABLE IF NOT EXISTS yel.admin_users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(120) NOT NULL,
  email VARCHAR(180) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  role TEXT NOT NULL DEFAULT 'support_agent' CHECK (role IN ('super_admin', 'listings_admin', 'orders_admin', 'support_agent', 'content_editor')),
  totp_secret VARCHAR(64) NULL,
  totp_enabled SMALLINT NOT NULL DEFAULT 0,
  active SMALLINT NOT NULL DEFAULT 1,
  last_login_at TIMESTAMPTZ NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS yel.admin_sessions (
  id VARCHAR(128) PRIMARY KEY,
  user_id BIGINT NOT NULL,
  ip_address VARCHAR(64) NULL,
  user_agent VARCHAR(255) NULL,
  expires_at TIMESTAMPTZ NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT fk_admin_sessions_user FOREIGN KEY (user_id) REFERENCES admin_users(id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS admin_sessions_user_idx ON yel.admin_sessions (user_id);
CREATE INDEX IF NOT EXISTS admin_sessions_expires_idx ON yel.admin_sessions (expires_at);

CREATE TABLE IF NOT EXISTS yel.admin_pending_logins (
  token VARCHAR(128) PRIMARY KEY,
  user_id BIGINT NOT NULL,
  setup_secret VARCHAR(64) NULL,
  expires_at TIMESTAMPTZ NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT fk_admin_pending_user FOREIGN KEY (user_id) REFERENCES admin_users(id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS admin_pending_expires_idx ON yel.admin_pending_logins (expires_at);

CREATE TABLE IF NOT EXISTS yel.activity_log (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NULL,
  actor_name VARCHAR(120) NOT NULL DEFAULT 'System',
  action VARCHAR(80) NOT NULL,
  entity_type VARCHAR(40) NOT NULL DEFAULT 'system',
  entity_id VARCHAR(64) NULL,
  details VARCHAR(500) NOT NULL DEFAULT '',
  metadata JSONB NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT fk_activity_log_user FOREIGN KEY (user_id) REFERENCES admin_users(id) ON DELETE SET NULL
);
CREATE INDEX IF NOT EXISTS activity_log_created_idx ON yel.activity_log (created_at);
CREATE INDEX IF NOT EXISTS activity_log_action_idx ON yel.activity_log (action);

CREATE TABLE IF NOT EXISTS yel.customers (
  id CHAR(36) PRIMARY KEY,
  full_name VARCHAR(120) NOT NULL,
  email VARCHAR(180) NULL UNIQUE,
  phone VARCHAR(32) NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  loyalty_tier TEXT NOT NULL DEFAULT 'standard' CHECK (loyalty_tier IN ('standard', 'corporate', 'vip')),
  city VARCHAR(100) NOT NULL DEFAULT '',
  notes TEXT NULL,
  active SMALLINT NOT NULL DEFAULT 1,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS yel.customer_sessions (
  id VARCHAR(128) PRIMARY KEY,
  customer_id CHAR(36) NOT NULL,
  expires_at TIMESTAMPTZ NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT fk_customer_sessions_customer FOREIGN KEY (customer_id) REFERENCES customers(id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS customer_sessions_customer_idx ON yel.customer_sessions (customer_id);
CREATE INDEX IF NOT EXISTS customer_sessions_expires_idx ON yel.customer_sessions (expires_at);

CREATE TABLE IF NOT EXISTS yel.jobs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug VARCHAR(180) NOT NULL UNIQUE,
  title VARCHAR(180) NOT NULL,
  destination_country VARCHAR(80) NOT NULL,
  destination_city VARCHAR(80) NOT NULL,
  role_category VARCHAR(80) NOT NULL,
  employer_name VARCHAR(160) NOT NULL DEFAULT 'Verified GCC Partner',
  openings_total INTEGER NOT NULL DEFAULT 1,
  openings_filled INTEGER NOT NULL DEFAULT 0,
  salary_amount DECIMAL(12,2) NULL,
  salary_currency VARCHAR(12) NOT NULL DEFAULT 'SAR',
  compensation_display VARCHAR(160) NOT NULL,
  contract_months INTEGER NOT NULL DEFAULT 24,
  requirements TEXT NOT NULL,
  benefits TEXT NOT NULL,
  deadline DATE NOT NULL,
  status TEXT NOT NULL DEFAULT 'Published' CHECK (status IN ('Published', 'Draft', 'Closed', 'Archived')),
  featured SMALLINT NOT NULL DEFAULT 1,
  created_by BIGINT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT fk_jobs_created_by FOREIGN KEY (created_by) REFERENCES admin_users(id) ON DELETE SET NULL
);
CREATE INDEX IF NOT EXISTS jobs_status_deadline_idx ON yel.jobs (status, deadline);

CREATE TABLE IF NOT EXISTS yel.job_applications (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  application_id CHAR(36) NOT NULL UNIQUE,
  tracking_code VARCHAR(32) NOT NULL UNIQUE,
  job_id BIGINT NULL,
  job_title VARCHAR(180) NOT NULL,
  destination VARCHAR(180) NOT NULL,
  full_name VARCHAR(120) NOT NULL,
  phone VARCHAR(32) NOT NULL,
  email VARCHAR(180) NOT NULL DEFAULT '',
  experience TEXT NULL,
  notes TEXT NULL,
  cv_name VARCHAR(255) NOT NULL,
  cv_type VARCHAR(140) NOT NULL,
  cv_size INTEGER NOT NULL,
  cv_data TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'New' CHECK (status IN ('New', 'Reviewed', 'Shortlisted', 'Visa Processing', 'Placed', 'Rejected')),
  staff_notes TEXT NULL,
  reviewed_by BIGINT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT fk_job_apps_job FOREIGN KEY (job_id) REFERENCES jobs(id) ON DELETE SET NULL,
  CONSTRAINT fk_job_apps_reviewer FOREIGN KEY (reviewed_by) REFERENCES admin_users(id) ON DELETE SET NULL
);
CREATE INDEX IF NOT EXISTS job_apps_status_created_idx ON yel.job_applications (status, created_at);
CREATE INDEX IF NOT EXISTS job_apps_job_idx ON yel.job_applications (job_id);
CREATE INDEX IF NOT EXISTS job_apps_phone_idx ON yel.job_applications (phone);

CREATE TABLE IF NOT EXISTS yel.job_application_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  job_application_id BIGINT NOT NULL,
  status VARCHAR(40) NOT NULL,
  note VARCHAR(500) NOT NULL DEFAULT '',
  updated_by_name VARCHAR(120) NOT NULL DEFAULT 'Recruitment Team',
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT fk_job_app_events_app FOREIGN KEY (job_application_id) REFERENCES job_applications(id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS job_app_events_app_idx ON yel.job_application_events (job_application_id, created_at);

CREATE TABLE IF NOT EXISTS yel.products (
  id CHAR(36) PRIMARY KEY,
  slug VARCHAR(180) NOT NULL UNIQUE,
  title VARCHAR(180) NOT NULL,
  division TEXT NOT NULL CHECK (division IN ('Vehicles', 'Real Estate', 'Sanitation', 'Other')),
  listing_kind TEXT NOT NULL DEFAULT 'general' CHECK (listing_kind IN ('vehicle_sale', 'vehicle_hire', 'property_sale', 'property_rent', 'short_stay', 'sanitation_package', 'general')),
  description TEXT NOT NULL,
  location VARCHAR(160) NOT NULL DEFAULT 'Kenya',
  specs JSONB NULL,
  image_urls JSONB NOT NULL,
  amount_kes BIGINT NOT NULL,
  price_unit TEXT NOT NULL DEFAULT 'total' CHECK (price_unit IN ('total', 'per_day', 'per_night', 'per_month', 'per_trip')),
  deposit_percent SMALLINT NOT NULL DEFAULT 100,
  stock_quantity INTEGER NOT NULL DEFAULT 1,
  status TEXT NOT NULL DEFAULT 'available' CHECK (status IN ('available', 'reserved', 'booked', 'sold', 'unavailable', 'draft', 'archived')),
  purchasable SMALLINT NOT NULL DEFAULT 1,
  featured SMALLINT NOT NULL DEFAULT 1,
  booking_kind TEXT NOT NULL DEFAULT 'none' CHECK (booking_kind IN ('none', 'car', 'short_stay', 'sanitation')),
  created_by BIGINT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT fk_products_created_by FOREIGN KEY (created_by) REFERENCES admin_users(id) ON DELETE SET NULL
);
CREATE INDEX IF NOT EXISTS products_division_status_idx ON yel.products (division, status, purchasable);

CREATE TABLE IF NOT EXISTS yel.carts (
  id CHAR(36) PRIMARY KEY,
  customer_id CHAR(36) NOT NULL UNIQUE,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT fk_carts_customer FOREIGN KEY (customer_id) REFERENCES customers(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS yel.cart_items (
  id CHAR(36) PRIMARY KEY,
  cart_id CHAR(36) NOT NULL,
  product_id CHAR(36) NOT NULL,
  quantity INTEGER NOT NULL DEFAULT 1,
  booking_details JSONB NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (cart_id, product_id),
  CONSTRAINT fk_cart_items_cart FOREIGN KEY (cart_id) REFERENCES carts(id) ON DELETE CASCADE,
  CONSTRAINT fk_cart_items_product FOREIGN KEY (product_id) REFERENCES products(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS yel.saved_items (
  customer_id CHAR(36) NOT NULL,
  product_id CHAR(36) NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (customer_id, product_id),
  CONSTRAINT fk_saved_items_customer FOREIGN KEY (customer_id) REFERENCES customers(id) ON DELETE CASCADE,
  CONSTRAINT fk_saved_items_product FOREIGN KEY (product_id) REFERENCES products(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS yel.orders (
  id CHAR(36) PRIMARY KEY,
  order_number VARCHAR(32) NOT NULL UNIQUE,
  customer_id CHAR(36) NOT NULL,
  checkout_key CHAR(36) NOT NULL,
  status TEXT NOT NULL DEFAULT 'Pending payment' CHECK (status IN ('Pending payment', 'Placed', 'Confirmed', 'In progress', 'Completed', 'Cancelled')),
  payment_status TEXT NOT NULL DEFAULT 'pending' CHECK (payment_status IN ('pending', 'paid', 'failed', 'cancelled')),
  currency VARCHAR(8) NOT NULL DEFAULT 'KES',
  total_amount BIGINT NOT NULL,
  cancel_requested_at TIMESTAMPTZ NULL,
  cancel_reason VARCHAR(500) NULL,
  notes TEXT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (customer_id, checkout_key),
  CONSTRAINT fk_orders_customer FOREIGN KEY (customer_id) REFERENCES customers(id) ON DELETE RESTRICT
);
CREATE INDEX IF NOT EXISTS orders_customer_created_idx ON yel.orders (customer_id, created_at);

CREATE TABLE IF NOT EXISTS yel.order_items (
  id CHAR(36) PRIMARY KEY,
  order_id CHAR(36) NOT NULL,
  product_id CHAR(36) NULL,
